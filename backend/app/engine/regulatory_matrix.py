def _check_apr_terms(text: str, origin: str, channel: str) -> bool:
    """Detects missing mandatory APR / representative financing terms."""
    has_credit_claim = bool(re.search(
        r"\b(0%\s*(?:financing|interest)|finance available|pay in installments?|monthly installments?|monthly payments?|\$\d+/mo(?:nth)?|£\d+/mo(?:nth)?|€\d+/mo(?:nth)?|spread the cost|split the payment|deferred payment|credit terms?)\b",
        text,
        re.IGNORECASE,
    ))
    has_apr_disclosure = bool(re.search(
        r"\b(\d+(?:\.\d+)?%\s*APR|APR terms? apply|representative APR|subject to credit approval|credit terms apply|statutory borrowing rate)\b",
        text,
        re.IGNORECASE,
    ))
    return has_credit_claim and not has_apr_disclosure


def _check_validity_window(text: str, origin: str, channel: str) -> bool:
    """Detects missing promotional validity windows or expiration dates."""
    has_promo = bool(re.search(
        r"\b(limited[- ]time offer|special promotional offer|save \d+%|\d+%\s+discount|\d+%\s+off|flash sale|early[- ]bird discount|promotional rate)\b",
        text,
        re.IGNORECASE,
    ))
    has_validity = bool(re.search(
        r"\b(valid (?:until|through|to)|offer ends|expires?|until (?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec|\d{4}-\d{2}-\d{2})|by \d{1,2}\s+[A-Z][a-z]+\s+\d{4}|while (?:supplies|places|stocks?) last|limited time offer\.? terms apply)\b",
        text,
        re.IGNORECASE,
    ))
    return has_promo and not has_validity


