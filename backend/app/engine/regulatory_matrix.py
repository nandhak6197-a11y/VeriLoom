def list_supported_jurisdictions() -> List[Dict[str, Any]]:
    """Returns metadata for all available regulatory regimes."""
    res = []
    for code, prof in JURISDICTION_PROFILES.items():
        if code == "GLOBAL":
            rule_count = sum(len(p["disclosures"]) for k, p in JURISDICTION_PROFILES.items() if k != "GLOBAL")
        else:
            rule_count = len(prof["disclosures"])
        res.append({
            "code": prof["code"],
            "name": prof["name"],
            "flag": prof["flag"],
            "statutes": prof["statutes"],
            "rule_count": rule_count,
        })
    return res


def evaluate_regulatory_compliance(
    text: str,
    origin: str = "employee",
    channel: str = "social",
    jurisdiction: str = "US",
) -> List[Dict[str, Any]]:
    """
    Evaluates text against the selected jurisdiction's mandatory legal requirements.
    Supports US (FTC), EU (AI Act Art 50 / Consumer Rights), UK (ASA/CMA / CAP Code), and Global standards.
    Detects missing mandatory disclosures: AI origin labels, sponsorship tags, APR terms, validity windows.
    Returns structured findings and synthesized non-destructive disclosure recommendations within channel character limits.
    """
    jurisdiction = (jurisdiction or "US").upper()
    active_jurisdictions = ["EU", "US", "UK"] if jurisdiction == "GLOBAL" else [jurisdiction]

    findings = []
    seen_rule_ids = set()
    channel_key = (channel or "social").lower()
    char_limit = CHANNEL_LIMITS.get(channel_key, 2000)
    cumulative_disclosure_length = 0
    base_length = len(text.strip())

    for jur_code in active_jurisdictions:
        profile = JURISDICTION_PROFILES.get(jur_code)
        if not profile:
            continue

        for disc_key, disc in profile["disclosures"].items():
            rule_id = disc["rule_id"]
            if rule_id in seen_rule_ids:
                continue

            # Run deterministic boolean check
            try:
                is_triggered = disc["check"](text, origin, channel_key)
            except Exception:
                is_triggered = False

            if is_triggered:
                seen_rule_ids.add(rule_id)
                disc_texts = disc["disclosure_text"]
                chosen_disclosure = disc_texts.get(
                    channel_key,
                    disc_texts.get("web", disc_texts.get("social", ""))
                )

                # Character capacity analysis (cumulative across co-occurring disclosures)
                sep_len = 2 if ("\n" in chosen_disclosure or "\n" in text) else 1
                disclosure_cost = len(chosen_disclosure) + sep_len
                cumulative_char_length = base_length + cumulative_disclosure_length + disclosure_cost
                fits_in_channel = cumulative_char_length <= char_limit

                # Accumulate for subsequent co-occurring findings
                cumulative_disclosure_length += disclosure_cost

                suggested_fix = inject_disclosure_into_text(text, chosen_disclosure, placement="append")

                findings.append({
                    "rule_id": rule_id,
                    "fact_id": "",
                    "jurisdiction": jur_code,
                    "jurisdiction_name": profile["name"],
                    "source_clause": f"{profile['name']} § {disc['clause']}",
                    "check_type": "regulatory_compliance",
                    "category": "legal_disclosure",
                    "base_severity": disc["severity"],
                    "verdict_tier": disc["severity"],
                    "severity": disc["severity"].lower(),
                    "high_risk": disc["severity"] == "Violation",
                    "span": "Missing Mandatory Regulatory Disclosure",
                    "explanation": (
                        f"Missing required disclosure under {profile['name']} ({disc['clause']}). "
                        f"Commercial content originating from '{origin}' via '{channel}' requires explicit disclaimer."
                    ),
                    "suggested_disclosure": chosen_disclosure,
                    "append_action": "APPEND_DISCLOSURE",
                    "channel": channel_key,
                    "channel_char_limit": char_limit,
                    "projected_length": cumulative_char_length,
                    "cumulative_disclosure_length": cumulative_disclosure_length,
                    "fits_in_channel": fits_in_channel,
                    "suggested_fix": suggested_fix,
                    "tracked_change": f"{text.strip()} {{+{chosen_disclosure}+}}",
                    "rationale": f"Appends non-destructive legal disclosure complying with {disc['clause']}.",
                    "stability_agreement": 1.0,
                    "stability_note": f"Deterministic statutory rule check ({profile['name']})",
                })

    return findings


def inject_disclosure_into_text(
    original_text: str,
    disclosure_text: str,
    placement: str = "append",
) -> str:
    """
    Surgically injects or appends a legal disclosure without mutating headline copy.
    Supports placements: 'append', 'prepend', 'footnote'.
    Guarantees non-destructive, idempotent application.
    """
    clean_orig = original_text.strip()
    clean_disc = disclosure_text.strip()

    if not clean_disc:
        return clean_orig

    if clean_disc in clean_orig:
        return clean_orig

    mode = (placement or "append").strip().lower()

    if mode == "prepend":
        return f"{clean_disc}\n\n{clean_orig}"
    elif mode == "footnote":
        return f"{clean_orig}\n\n---\n{clean_disc}"
    elif mode == "append":
        if "\n" in clean_orig:
            return f"{clean_orig}\n\n{clean_disc}"
        else:
            return f"{clean_orig} {clean_disc}"
    else:
        # Default append
        if "\n" in clean_orig:
            return f"{clean_orig}\n\n{clean_disc}"
        else:
            return f"{clean_orig} {clean_disc}"
